//! Zobrist hashing: the key table a position's hash is built from.
//!
//! Exercise 02, part 2 — see `docs/exercises/02-pieces-and-position.md`.
//! The spec is `tests/zobrist.rs`, which cannot go fully green until
//! [`Position`](crate::Position) can be built from a FEN.
//!
//! # Why a hash at all
//!
//! A search visits the same position by different move orders constantly —
//! `1. e4 e5 2. Nf3` and `1. Nf3 e5 2. e4` reach the same board. The
//! transposition table catches that and reuses the result, but it needs a key:
//! a `u64` that identifies a position and is cheap to keep current.
//!
//! # Why it is a giant XOR
//!
//! ```text
//! hash = key[piece][square] for every piece on the board
//!      ^ key[castling rights]
//!      ^ key[en passant file]      (only if there is one)
//!      ^ key[black to move]        (only if black to move)
//! ```
//!
//! XOR is its own inverse, which is the entire point. Moving a rook from a1 to
//! d1 is two XORs and no rescan:
//!
//! ```text
//! hash ^= key[WHITE_ROOK][A1];   // it is no longer there
//! hash ^= key[WHITE_ROOK][D1];   // it is here now
//! ```
//!
//! Same "patch, don't recompute" idea as the NNUE accumulator, needed on the
//! same code path — which is why both are settled before `make_move` exists.
//! In this exercise there are no moves yet, so you only compute a hash from
//! scratch. Having the scheme fixed now means make/unmake only adds XORs.
//!
//! # Why the keys are compile-time constants
//!
//! A hash means nothing across runs if the keys differ per run — an opening
//! book, a stored table, a debug trace comparing two sessions all become
//! garbage. So the table is generated by a `const fn` running a deterministic
//! PRNG from a literal seed, and is byte-identical on every build.

use crate::{CastlingRights, File, Piece, Square};

/// Every key the hash is built from.
///
/// Note the shape of `en_passant`: **keyed by file, not by square**. The rank
/// of an en passant target is determined by whose turn it is, so the file is
/// all the information there is. Eight keys, not 64.
///
/// The clocks are deliberately absent. A transposition table stores a search
/// result for a position, and that result depends on the pieces, the rights and
/// whose turn it is — not on how long it has been since a pawn moved. Including
/// them would make two identical positions reached by different move orders
/// miss each other in the table, which is exactly the saving the table exists
/// for. The cost is that the fifty-move rule has to be handled by the search
/// itself; that is the standard trade.
pub(crate) struct Keys {
    /// One key per `(piece, square)` pair, indexed by [`Piece::index`].
    pieces: [[u64; 64]; 12],
    /// One key per castling-rights combination, indexed by
    /// [`CastlingRights::index`].
    castling: [u64; 16],
    /// One key per en passant file.
    en_passant: [u64; 8],
    /// Folded into the hash only when it is Black's turn.
    black_to_move: u64,
}

/// The one key table, built at compile time.
///
/// A `static` and not a `LazyLock`: [`Keys::generate`] is a `const fn`, so this
/// costs nothing at startup and the bytes live in the binary.
pub(crate) static KEYS: Keys = Keys::generate();

impl Keys {
    /// The PRNG seed.
    ///
    /// A literal, and it must stay one — changing it invalidates every hash
    /// ever written down. (This value is the golden ratio in fixed point, a
    /// conventional choice for nothing-up-my-sleeve constants.)
    const SEED: u64 = 0x9E37_79B9_7F4A_7C15;

    /// Draws all 793 keys from [`SEED`](Keys::SEED), at compile time.
    ///
    /// `while` rather than `for`, which a `const fn` cannot use. The fill
    /// order is arbitrary but must stay fixed: changing it renumbers every
    /// key, exactly as changing the seed would.
    const fn generate() -> Self {
        let mut rng = Rng { state: Self::SEED };

        let mut pieces = [[0u64; 64]; 12];
        let mut piece = 0;
        while piece < 12 {
            let mut square = 0;
            while square < 64 {
                pieces[piece][square] = rng.next();
                square += 1;
            }
            piece += 1;
        }

        let mut castling = [0u64; 16];
        let mut rights = 0;
        while rights < 16 {
            castling[rights] = rng.next();
            rights += 1;
        }

        let mut en_passant = [0u64; 8];
        let mut file = 0;
        while file < 8 {
            en_passant[file] = rng.next();
            file += 1;
        }

        let black_to_move = rng.next();

        Self {
            pieces,
            castling,
            en_passant,
            black_to_move,
        }
    }

    /// The key for this piece standing on this square.
    ///
    /// Indexing lives here and nowhere else, so that a transposed index is one
    /// bug in one place rather than a subtle search failure months later —
    /// which is what `tests/zobrist.rs::every_piece_on_every_square_has_its_own_key`
    /// is watching for.
    pub(crate) const fn piece(&self, piece: Piece, square: Square) -> u64 {
        self.pieces[piece.index()][square.index() as usize]
    }

    /// The key for this combination of castling rights.
    pub(crate) const fn castling(&self, rights: CastlingRights) -> u64 {
        self.castling[rights.index()]
    }

    /// The key for an en passant target on this file.
    pub(crate) const fn en_passant(&self, file: File) -> u64 {
        self.en_passant[file.index() as usize]
    }

    /// The key folded into the hash when it is Black's turn.
    pub(crate) const fn black_to_move(&self) -> u64 {
        self.black_to_move
    }
}

/// xorshift64. Well-spread, not cryptographic, and zero is an absorbing state
/// — so [`Keys::SEED`] must stay non-zero.
struct Rng {
    state: u64,
}

impl Rng {
    const fn next(&mut self) -> u64 {
        let mut x = self.state;
        x ^= x << 13;
        x ^= x >> 7;
        x ^= x << 17;
        self.state = x;
        x
    }
}
